export function monsterCharacter(
  template: (typeof MONSTERS)[number],
  id: string,
): Character {
  const c = newCharacter(id, "");
  const m = template;
  const image = BASE_ART.find(
    (a) =>
      a.source.endsWith("/" + m.art) &&
      (!m.art.startsWith("pipo") || a.source.includes("non shade")),
  );
  return {
    ...c,
    name: m.name,
    kind: "npc",
    side: "foes",
    public: false,
    custom: true,
    identity: `Lv ${m.level} · ${m.species}`,
    theme: "",
    origin: `核心书 20230207 · 怪物图鉴 ${m.page} 页`,
    description: m.description + "\n伤害亲和度：" + m.affinities,
    classes: [{ id: "bestiary", name: m.species, level: m.level, skills: {} }],
    attrs: {
      dex: m.attrs[0],
      ins: m.attrs[1],
      mig: m.attrs[2],
      wlp: m.attrs[3],
    },
    overrides: {
      hp: m.hp,
      mp: m.mp,
      ip: 0,
      def: m.def,
      mdef: m.mdef,
      initiative: m.init,
    },
    hp: m.hp,
    mp: m.mp,
    ip: 0,
    zenit: 0,
    fabula: 0,
    equipment: [],
    gearNotes:
      "数值已包含图鉴列出的装备；勿重复计算。立绘为独立素材包的外形匹配，并非官方插图。",
    portrait: image?.id ?? "",
    abilities: m.abilities.map((a, i) => ({
      ...a,
      id: `monster-${m.id}-${i}`,
      source: `核心书 ${m.page} 页`,
    })),
  };
}
